package compiler

import (
	"fmt"
	"kat/ast"
	"kat/code"
	"kat/value"
)

const (
	BOGUS_JUMP = 9999
)

type Compiler struct {
	instructions code.Instructions // hold generated bytecode
	constants    []value.Value     // hold constant pool
}

type Bytecode struct {
	Instructions code.Instructions
	Constants    []value.Value
}

func New() *Compiler {
	return &Compiler{
		instructions: code.Instructions{},
		constants:    []value.Value{},
	}
}

func (c *Compiler) Compile(astNode ast.Node) error {
	switch stmt := astNode.(type) {

	case *ast.NodeProgram:
		return c.compileProgram(stmt)

	case *ast.NodeExprStmt:
		e := c.Compile(stmt.Expr)

		if e != nil {
			return e
		}

		c.emit(code.OpPop)

	case *ast.NodeInfixExpr:
		if e := c.Compile(stmt.Left); e != nil {
			return e
		}

		if e := c.Compile(stmt.Right); e != nil {
			return e
		}

		switch stmt.Operator {
		case "+":
			c.emit(code.OpAdd)

		case "-":
			c.emit(code.OpSub)

		case "*":
			c.emit(code.OpMul)

		case "/":
			c.emit(code.OpDiv)

		case ">":
			c.emit(code.OpGreaterThan)

		case "<":
			c.emit(code.OpLessThan)

		case "==":
			c.emit(code.OpEqual)

		case "!=":
			c.emit(code.OpNotEqual)

		default:
			return fmt.Errorf("unknown operator: %s", stmt.Operator)
		}

	case *ast.NodeInteger:
		val := &value.Int{Value: stmt.Value}
		c.emit(code.OpConstant, c.addConstant(val))

	case *ast.NodeBoolean:
		if stmt.Value {
			c.emit(code.OpTrue)
		} else {
			c.emit(code.OpFalse)
		}

	case *ast.NodePrefixExpr:
		if err := c.Compile(stmt.Right); err != nil {
			return err
		}

		switch stmt.Operator {
		case "-":
			c.emit(code.OpMinus)
		case "!":
			c.emit(code.OpBang)
		default:
			return fmt.Errorf("Unknow operator %s", stmt.Operator)
		}

	case *ast.NodeBlockStmt:
		for _, node := range stmt.Body {
			e := c.Compile(node)

			if e != nil {
				return e
			}
		}

	case *ast.NodeConditionalStmt:
		//
		//	if (true) {
		//		10
		//	} else {
		//     22
		//	}
		// 	33;
		//

		// Put the `true` on the stack
		if err := c.Compile(stmt.Condition); err != nil {
			return err
		}

		// Emit jump if false
		ifFalseJumpPos := c.emit(code.OpJumpIfFalse, BOGUS_JUMP)

		// Compile the `then` arm
		if err := c.Compile(stmt.ThenArm); err != nil {
			return err
		}

		// Compile the `else` arm
		if stmt.ElseArm != nil {
			jumpPos := c.emit(code.OpJump, BOGUS_JUMP)
			afterJumpPos := len(c.instructions)

			c.changeOperand(ifFalseJumpPos, afterJumpPos)

			if err := c.Compile(stmt.ElseArm); err != nil {
				return err
			}

			afterElseArmPos := len(c.instructions)
			c.changeOperand(jumpPos, afterElseArmPos)
		} else {
			jumpPos := c.emit(code.OpJump, BOGUS_JUMP)
			afterThenArmPos := len(c.instructions)
			c.changeOperand(ifFalseJumpPos, afterThenArmPos)

			c.emit(code.OpNull) // Emit `else` block in case there is no any
			c.emit(code.OpPop)  // Emit code.OpPop so it left `null` on the top of stack

			afterElseArmPos := len(c.instructions)
			c.changeOperand(jumpPos, afterElseArmPos)
		}
	}

	return nil
}

func (c *Compiler) changeOperand(opCodePos int, operand int) {
	opCode := code.Opcode(c.instructions[opCodePos])
	instruction := code.Make(opCode, operand)
	c.replaceInstruction(opCodePos, instruction)
}

func (c *Compiler) replaceInstruction(opCodePos int, instruction []byte) {
	for i := 0; i < len(instruction); i++ {
		c.instructions[opCodePos+i] = instruction[i]
	}
}

func (c *Compiler) addConstant(val value.Value) int {
	c.constants = append(c.constants, val)
	return len(c.constants) - 1
}

func (c *Compiler) emit(opCode code.Opcode, operands ...int) int {
	instruction := code.Make(opCode, operands...)
	return c.addInstruction(instruction)
}

func (c *Compiler) addInstruction(instruction []byte) int {
	posOfNewInstruction := len(c.instructions)
	c.instructions = append(c.instructions, instruction...)
	return posOfNewInstruction
}

func (c *Compiler) compileProgram(node *ast.NodeProgram) error {
	for _, stmt := range node.Body {
		e := c.Compile(stmt)

		if e != nil {
			return e
		}
	}

	return nil
}

func (c *Compiler) Bytecode() *Bytecode {
	return &Bytecode{
		Instructions: c.instructions,
		Constants:    c.constants,
	}
}
